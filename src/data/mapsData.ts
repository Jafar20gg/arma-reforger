export function getMapWithOverrides(
  mapDef: MapDefinition,
  overrides?: Record<string, { xMeters: number; yMeters: number; altitudeMeters: number; isCustomized?: boolean }>
): MapDefinition {
  if (!overrides || Object.keys(overrides).length === 0) {
    return {
      ...mapDef,
      controlPoints: mapDef.controlPoints.map(cp => ({
        ...cp,
        isVerified: true,
        isUserCustomized: false,
        verifiedSource: 'Enfusion Engine World Data',
      })),
    };
  }

  const mergedPoints = mapDef.controlPoints.map(cp => {
    const override = overrides[cp.id];
    if (!override) {
      return {
        ...cp,
        isVerified: true,
        isUserCustomized: false,
        verifiedSource: 'Enfusion Engine World Data',
      };
    }
    return {
      ...cp,
      xMeters: override.xMeters,
      yMeters: override.yMeters,
      altitudeMeters: override.altitudeMeters,
      isVerified: false,
      isUserCustomized: true,
      verifiedSource: 'User Customized Coordinate',
    };
  });

  return {
    ...mapDef,
    controlPoints: mergedPoints,
  };
}
